import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { mkdir, mkdtemp, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { promisify } from 'node:util';
const run = promisify(execFile);
const [version, ref, ...extra] = process.argv.slice(2);
assert.ok(version && /^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(version) && ref && !extra.length, 'Usage: npm run docs:archive -- VERSION GIT_REF');
assert.ok(!version.startsWith('0.'), 'Documentation snapshots start with v1; pre-v1 docs stay current-only');
const commit = (await run('git', ['rev-parse', '--verify', '--end-of-options', ref + '^{commit}'])).stdout.trim();
const show = async (file: string) => (await run('git', ['show', `${commit}:${file}`], { maxBuffer: 4 * 1024 * 1024 })).stdout;
assert.equal(JSON.parse(await show('packages/core/package.json')).version, version, 'Git ref must contain the requested core version');
const root = resolve('docs/versions');
await mkdir(root, { recursive: true });
const staging = await mkdtemp(join(root, '.archive-'));
try {
  const files = (await run('git', ['ls-tree', '-r', '--name-only', commit, 'docs/guide'])).stdout.trim().split('\n').filter(file => /^docs\/guide\/(en|it)\/[a-z-]+\.md$/.test(file));
  assert.ok(files.length, 'No released guides found');
  const sha256: Record<string, string> = {};
  for (const file of files) {
    const target = join(staging, file.slice('docs/guide/'.length));
    await mkdir(join(target, '..'), { recursive: true });
    const source = await show(file);
    await writeFile(target, source);
    sha256[file.slice('docs/guide/'.length)] = createHash('sha256').update(source).digest('hex');
  }
  const navigation = await show('src/app/docs/navigation.ts');
  await writeFile(join(staging, 'navigation.ts'), navigation);
  sha256['navigation.ts'] = createHash('sha256').update(navigation).digest('hex');
  await writeFile(join(staging, 'release.json'), JSON.stringify({ version, slug: version.replaceAll('.', '-'), ref: commit, sha256 }, null, 2) + '\n');
  // Refuse to replace a previously archived version, even when directories are empty.
  assert.ok(!(await readdir(root)).includes(version), 'Documentation version already archived');
  await rename(staging, join(root, version));
} finally { await rm(staging, { recursive: true, force: true }); }
const archives = [];
for (const directory of (await readdir(root)).filter(name => !name.startsWith('.')).sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))) {
  const metadata = JSON.parse(await readFile(join(root, directory, 'release.json'), 'utf8'));
  assert.equal(metadata.version, directory);
  archives.push({ version: String(metadata.version), slug: String(metadata.slug), ref: String(metadata.ref) });
}
assert.equal(new Set(archives.map(archive => archive.slug)).size, archives.length, 'Documentation URL slugs must be unique');
await writeFile('src/app/docs/archives.ts', '// Generated by docs:archive. Archived guides are read-only snapshots.\n' + archives.map((archive, i) => `import { guideNavigation as navigation${i} } from '../../../docs/versions/${archive.version}/navigation';`).join('\n') + '\nexport const archivedDocumentation = [\n' + archives.map((archive, i) => `  { ...${JSON.stringify(archive)}, guides: navigation${i} },`).join('\n') + '\n] as const;\n');
console.log(`Archived ${version} from ${commit}`);
